    public static LogEntry Localize(LogEntry entry)
    {
        if (LocalizationService.CurrentLanguage != "en") return entry;

        var message = SchedulerPanelViewModel.LocalizeLogMessage(entry.Message);
        message = TranslateMessage(message);
        return entry with
        {
            Category = TranslateCategory(entry.Category),
            Message = message
        };
    }

